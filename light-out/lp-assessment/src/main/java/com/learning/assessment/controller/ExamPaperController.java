package com.learning.assessment.controller;

import com.learning.assessment.dto.PaperAutoGenerateDTO;
import com.learning.assessment.dto.PaperCreateDTO;
import com.learning.assessment.dto.PaperPublishDTO;
import com.learning.assessment.service.ExamPaperService;
import com.learning.assessment.vo.ExamPaperVO;
import com.learning.assessment.vo.TaskVO;
import com.learning.lpcommon.result.PageResult;
import com.learning.lpcommon.result.Result;
import jakarta.annotation.Resource;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/paper")
public class ExamPaperController {

    @Resource
    private ExamPaperService examPaperService;

    @PostMapping("/create")
    public Result<ExamPaperVO> create(@RequestBody PaperCreateDTO dto) {
        return Result.success(examPaperService.createPaper(dto));
    }

    @PostMapping("/autoGenerate")
    public Result<ExamPaperVO> autoGenerate(@RequestBody PaperAutoGenerateDTO dto) {
        return Result.success(examPaperService.autoGenerate(dto));
    }

    @PutMapping("/update")
    public Result<ExamPaperVO> update(@RequestBody PaperCreateDTO dto) {
        return Result.success(examPaperService.updatePaper(dto));
    }

    @DeleteMapping("/{paperId}")
    public Result<String> delete(@PathVariable Long paperId) {
        examPaperService.deletePaper(paperId);
        return Result.success("删除成功");
    }

    @GetMapping("/{paperId}")
    public Result<ExamPaperVO> detail(@PathVariable Long paperId) {
        return Result.success(examPaperService.getPaperDetail(paperId));
    }

    @GetMapping("/list/{courseId}")
    public Result<PageResult> list(@PathVariable Long courseId,
                                   @RequestParam(defaultValue = "1") Integer page,
                                   @RequestParam(defaultValue = "10") Integer pageSize) {
        return Result.success(examPaperService.listPapersByCourse(courseId, page, pageSize));
    }

    @PostMapping("/publish")
    public Result<TaskVO> publish(@RequestBody PaperPublishDTO dto) {
        return Result.success(examPaperService.publish(dto));
    }
}
