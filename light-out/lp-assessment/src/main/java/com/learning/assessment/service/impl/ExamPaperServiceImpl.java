import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

@Service
public class ExamPaperServiceImpl implements ExamPaperService {

    private static final Set<String> PUBLISH_TASK_TYPES = Set.of("quiz", "assignment");

    @Resource
    private ExamPaperMapper examPaperMapper;
    @Resource
    private PaperQuestionMapper paperQuestionMapper;
    @Resource
    private QuestionBankMapper questionBankMapper;
    @Resource
    private TaskService taskService;
    @Resource
    private AssessmentAccessGuard accessGuard;

    // ========== 手工组卷 ==========

    @Override
    @Transactional(rollbackFor = Exception.class)
    public ExamPaperVO createPaper(PaperCreateDTO dto) {
        accessGuard.requireTeaching("创建试卷");
        accessGuard.requireCourseTeacher(dto == null ? null : dto.getCourseId(), "创建试卷");
        validateBase(dto.getCourseId(), dto.getTitle());
        List<PaperQuestionItemDTO> items = dto.getItems();
        if (items == null || items.isEmpty()) {
            throw new BaseException("试卷至少需要一道题目");
        }
        List<PaperQuestionItemDTO> validated = validateItems(dto.getCourseId(), items);

        ExamPaper paper = buildPaper(dto.getCourseId(), dto.getTitle(), dto.getDuration(),
                dto.getShuffleQuestions(), sumScore(validated));
        examPaperMapper.insert(paper);
        insertQuestions(paper.getPaperId(), validated);
        return getPaperDetail(paper.getPaperId());
    }

    // ========== 自动抽题 ==========

    @Override
    @Transactional(rollbackFor = Exception.class)
    public ExamPaperVO autoGenerate(PaperAutoGenerateDTO dto) {
        accessGuard.requireTeaching("自动组卷");
        accessGuard.requireCourseTeacher(dto == null ? null : dto.getCourseId(), "自动组卷");
        validateBase(dto.getCourseId(), dto.getTitle());
        List<PaperAutoRuleDTO> rules = dto.getRules();
        if (rules == null || rules.isEmpty()) {
            throw new BaseException("抽题规则不能为空");
        }

        List<PaperQuestionItemDTO> items = new ArrayList<>();
        Set<Long> usedQIds = new HashSet<>();
        BigDecimal total = BigDecimal.ZERO;
        for (int i = 0; i < rules.size(); i++) {
            PaperAutoRuleDTO rule = rules.get(i);
            validateRule(rule);
            List<QuestionBank> drawn = questionBankMapper.selectRandomByConditions(
                    dto.getCourseId(), rule.getQType(), rule.getDifficulty(), rule.getCount());
            if (drawn.size() < rule.getCount()) {
                throw new BaseException("抽题规则[" + (i + 1) + "]题库数量不足：需要"
                        + rule.getCount() + "道，实际仅" + drawn.size() + "道");
            }
            List<QuestionBank> usable = new ArrayList<>();
            for (QuestionBank q : drawn) {
                if (!usedQIds.contains(q.getQId())) {
                    usedQIds.add(q.getQId());
                    usable.add(q);
                }
            }
            if (usable.size() < rule.getCount()) {
                throw new BaseException("抽题规则[" + (i + 1) + "]与已抽题目重叠过多，请调整规则或减少抽题数量");
            }
            for (QuestionBank q : usable) {
                PaperQuestionItemDTO item = new PaperQuestionItemDTO();
                item.setQId(q.getQId());
                item.setScore(rule.getScore());
                items.add(item);
                total = total.add(rule.getScore());
            }
        }

        ExamPaper paper = buildPaper(dto.getCourseId(), dto.getTitle(), dto.getDuration(),
                dto.getShuffleQuestions(), total);
        examPaperMapper.insert(paper);
        insertQuestions(paper.getPaperId(), items);
        return getPaperDetail(paper.getPaperId());
    }

    // ========== 更新 / 删除 / 查询 ==========

    @Override
    @Transactional(rollbackFor = Exception.class)
    public ExamPaperVO updatePaper(PaperCreateDTO dto) {
        if (dto.getPaperId() == null) {
            throw new BaseException("paperId 不能为空");
        }
        ExamPaper existing = examPaperMapper.selectById(dto.getPaperId());
        if (existing == null) {
            throw new BaseException("试卷不存在");
        }
        accessGuard.requireTeaching("修改试卷");
        accessGuard.requireCourseTeacher(existing.getCourseId(), "修改试卷");
        if (dto.getVersion() == null) {
            throw new BaseException("乐观锁版本号不能为空");
        }
        validateBase(dto.getCourseId(), dto.getTitle());

        List<PaperQuestionItemDTO> items = dto.getItems();
        if (items != null && !items.isEmpty()) {
            items = validateItems(dto.getCourseId(), items);
        }

        ExamPaper paper = buildPaper(dto.getCourseId(), dto.getTitle(), dto.getDuration(),
                dto.getShuffleQuestions(),
                items == null || items.isEmpty() ? existing.getTotalScore() : sumScore(items));
        paper.setPaperId(dto.getPaperId());
        paper.setVersion(dto.getVersion());
        int rows = examPaperMapper.update(paper);
        if (rows == 0) {
            throw new BaseException("试卷已被他人修改，请刷新后重试");
        }

        if (items != null && !items.isEmpty()) {
            paperQuestionMapper.deleteByPaperId(dto.getPaperId());
            insertQuestions(dto.getPaperId(), items);
        }
        return getPaperDetail(dto.getPaperId());
    }

    @Override
    @Transactional(rollbackFor = Exception.class)
    public void deletePaper(Long paperId) {
        ExamPaper existing = examPaperMapper.selectById(paperId);
        if (existing == null) {
            throw new BaseException("试卷不存在");
        }
        accessGuard.requireTeaching("删除试卷");
        accessGuard.requireCourseTeacher(existing.getCourseId(), "删除试卷");
        paperQuestionMapper.deleteByPaperId(paperId);
        examPaperMapper.deleteById(paperId);
    }

    @Override
    public ExamPaperVO getPaperDetail(Long paperId) {
        ExamPaper paper = examPaperMapper.selectById(paperId);
        if (paper == null) {
            throw new BaseException("试卷不存在");
        }
        List<PaperQuestion> pqs = paperQuestionMapper.selectByPaperId(paperId);
        // 脱敏：只有教师端能看到参考答案与解析；学生端（含考试进行中）只下发题干与选项
        boolean includeReference = accessGuard.isTeaching();
        List<PaperQuestionVO> questions = new ArrayList<>();
        for (PaperQuestion pq : pqs) {
            QuestionBank q = questionBankMapper.selectById(pq.getQId());
            if (q == null) {
                continue;
            }
            questions.add(PaperQuestionVO.builder()
                    .qId(q.getQId())
                    .qType(q.getQType())
                    .content(q.getContent())
                    .options(QuestionValidator.parseJsonList(q.getOptions()))
                    .answer(includeReference ? q.getAnswer() : null)
                    .analysis(includeReference ? q.getAnalysis() : null)
                    .difficulty(q.getDifficulty())
                    .score(pq.getScore())
                    .sortOrder(pq.getSortOrder())
                    .build());
        }
        return ExamPaperVO.fromEntity(paper, questions);
    }

    @Override
    public PageResult listPapersByCourse(Long courseId, Integer page, Integer pageSize) {
        if (courseId == null) {
            throw new BaseException("课程ID不能为空");
        }
        int p = (page == null || page < 1) ? 1 : page;
        int ps = (pageSize == null || pageSize < 1) ? 10 : pageSize;
        long total = examPaperMapper.countByCourseId(courseId);
        List<ExamPaperVO> records = examPaperMapper.selectByCourseIdPage(courseId, (p - 1) * ps, ps)
                .stream()
                .map(ExamPaperVO::fromEntity)
                .toList();
        return PageResult.build(records, total, (long) p, (long) ps);
    }

    // ========== 发布为作业/考试 ==========

    @Override
    @Transactional(rollbackFor = Exception.class)
    public TaskVO publish(PaperPublishDTO dto) {
        if (dto.getPaperId() == null) {
            throw new BaseException("paperId 不能为空");
        }
        ExamPaper paper = examPaperMapper.selectById(dto.getPaperId());
        if (paper == null) {
            throw new BaseException("试卷不存在");
        }
        if (dto.getCourseId() == null || !dto.getCourseId().equals(paper.getCourseId())) {
            throw new BaseException("课程ID与试卷不一致");
        }
        accessGuard.requireTeaching("发布试卷");
        accessGuard.requireCourseTeacher(paper.getCourseId(), "发布试卷");
        if (dto.getTaskType() == null || !PUBLISH_TASK_TYPES.contains(dto.getTaskType())) {
            throw new BaseException("任务类型仅支持 quiz-测验/考试 或 assignment-作业");
        }

        TaskCreateDTO taskDto = new TaskCreateDTO();
        taskDto.setCourseId(dto.getCourseId());
        taskDto.setTitle(dto.getTitle() != null && !dto.getTitle().isBlank() ? dto.getTitle() : paper.getTitle());
        taskDto.setDescription(dto.getDescription());
        taskDto.setTaskType(dto.getTaskType());
        taskDto.setTag(dto.getTag());
        taskDto.setWeight(dto.getWeight());
        taskDto.setPublishType(dto.getPublishType());
        taskDto.setPublishTime(dto.getPublishTime());
        taskDto.setDeadline(dto.getDeadline());
        taskDto.setAllowLate(dto.getAllowLate());
        taskDto.setLatePenalty(dto.getLatePenalty());
        taskDto.setMaxScore(dto.getMaxScore() != null ? dto.getMaxScore() : paper.getTotalScore());
        taskDto.setAllowResubmit(dto.getAllowResubmit());

        TaskVO taskVO = taskService.createTask(taskDto);
        examPaperMapper.updateTaskId(paper.getPaperId(), taskVO.getTaskId());
        return taskVO;
    }

    // ========== 内部方法 ==========

    private void validateBase(Long courseId, String title) {
        if (courseId == null) {
            throw new BaseException("课程ID不能为空");
        }
        if (title == null || title.isBlank()) {
            throw new BaseException("试卷标题不能为空");
        }
    }

    private void validateRule(PaperAutoRuleDTO rule) {
        if (rule.getQType() == null || !QuestionValidator.Q_TYPES.contains(rule.getQType())) {
            throw new BaseException("抽题规则题型不合法");
        }
        if (rule.getDifficulty() != null && (rule.getDifficulty() < 1 || rule.getDifficulty() > 3)) {
            throw new BaseException("抽题规则难度必须为1/2/3");
        }
        if (rule.getCount() == null || rule.getCount() <= 0) {
            throw new BaseException("抽题规则题目数量必须大于0");
        }
        if (rule.getScore() == null || rule.getScore().compareTo(BigDecimal.ZERO) <= 0) {
            throw new BaseException("抽题规则每题分值必须大于0");
        }
    }

    private List<PaperQuestionItemDTO> validateItems(Long courseId, List<PaperQuestionItemDTO> items) {
        Set<Long> seen = new HashSet<>();
        List<PaperQuestionItemDTO> validated = new ArrayList<>();
        for (PaperQuestionItemDTO item : items) {
            if (item.getQId() == null) {
                throw new BaseException("题目ID不能为空");
            }
            if (item.getScore() == null || item.getScore().compareTo(BigDecimal.ZERO) <= 0) {
                throw new BaseException("每题分值必须大于0");
            }
            if (!seen.add(item.getQId())) {
                throw new BaseException("试卷中不允许重复题目，题目ID: " + item.getQId());
            }
            QuestionBank q = questionBankMapper.selectById(item.getQId());
            if (q == null) {
                throw new BaseException("题目不存在，题目ID: " + item.getQId());
            }
            if (!courseId.equals(q.getCourseId())) {
                throw new BaseException("题目不属于该课程，题目ID: " + item.getQId());
            }
            validated.add(item);
        }
        return validated;
    }

    private BigDecimal sumScore(List<PaperQuestionItemDTO> items) {
        return items.stream()
                .map(PaperQuestionItemDTO::getScore)
                .reduce(BigDecimal.ZERO, BigDecimal::add);
    }

    private ExamPaper buildPaper(Long courseId, String title, Integer duration,
                                 Integer shuffleQuestions, BigDecimal totalScore) {
        ExamPaper paper = new ExamPaper();
        paper.setCourseId(courseId);
        paper.setTitle(title);
        paper.setDuration(duration);
        paper.setShuffleQuestions(shuffleQuestions != null ? shuffleQuestions : 0);
        paper.setTotalScore(totalScore);
        return paper;
    }

    private void insertQuestions(Long paperId, List<PaperQuestionItemDTO> items) {
        for (int i = 0; i < items.size(); i++) {
            PaperQuestionItemDTO item = items.get(i);
            PaperQuestion pq = new PaperQuestion();
            pq.setPaperId(paperId);
            pq.setQId(item.getQId());
            pq.setScore(item.getScore());
            pq.setSortOrder(i + 1);
            paperQuestionMapper.insert(pq);
        }
    }
}
