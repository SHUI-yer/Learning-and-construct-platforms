package com.learning.assessment.dto;

import com.learning.lpcommon.validation.ValidationGroups;
import jakarta.validation.Validation;
import jakarta.validation.Validator;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertTrue;

class AssessmentDtoValidationTest {

    private final Validator validator = Validation.buildDefaultValidatorFactory().getValidator();

    @Test
    void validatesNestedAutoPaperRules() {
        PaperAutoRuleDTO rule = new PaperAutoRuleDTO();
        rule.setQType("unknown");
        rule.setCount(0);
        rule.setScore(BigDecimal.ZERO);
        PaperAutoGenerateDTO dto = new PaperAutoGenerateDTO();
        dto.setCourseId(1L);
        dto.setTitle("自动组卷");
        dto.setRules(List.of(rule));

        assertTrue(validator.validate(dto).size() >= 3);
    }

    @Test
    void updateGroupRequiresTaskId() {
        TaskCreateDTO dto = new TaskCreateDTO();
        dto.setCourseId(1L);
        dto.setTitle("期末考试");
        dto.setTaskType("quiz");
        dto.setPublishType("immediate");
        dto.setDeadline(java.time.LocalDateTime.now().plusDays(1));

        assertTrue(validator.validate(dto, ValidationGroups.Update.class).stream()
                .anyMatch(violation -> "taskId".equals(violation.getPropertyPath().toString())));
    }

    @Test
    void validatesNestedSubmissionAnswers() {
        SubmissionSubmitDTO.AnswerItem answer = new SubmissionSubmitDTO.AnswerItem();
        SubmissionSubmitDTO dto = new SubmissionSubmitDTO();
        dto.setTaskId(1L);
        dto.setAnswers(List.of(answer));

        assertTrue(validator.validate(dto).stream()
                .anyMatch(violation -> violation.getPropertyPath().toString().contains("qId")));
    }
}
